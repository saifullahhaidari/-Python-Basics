# Comparison Operators in Python

a = 20
b = 10

print("a =", a)
print("b =", b)

print("a == b :", a == b)
print("a != b :", a != b)
print("a > b  :", a > b)
print("a < b  :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)
