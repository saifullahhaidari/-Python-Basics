# String
name = "Saifullah Haidari"

# Integer
age = 25

# Float
gpa = 3.85

# Boolean
is_student = True

print("===== Data Types =====")

print(f"Name: {name}")
print(f"Type: {type(name)}")

print(f"\nAge: {age}")
print(f"Type: {type(age)}")

print(f"\nGPA: {gpa}")
print(f"Type: {type(gpa)}")

print(f"\nStudent: {is_student}")
print(f"Type: {type(is_student)}")

